"""Optional natural-language tool backed by Google Gemini.

Gemini is an external LLM. It does not run any of RFM's numeric engines; tool results
say so explicitly so a client never mistakes Gemini's prose for RFM output.
"""

from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any, Optional

import httpx
from mcp.server.fastmcp import FastMCP
from mcp.server.fastmcp.exceptions import ToolError
from mcp.types import ToolAnnotations

API_BASE = "https://generativelanguage.googleapis.com/v1beta"
DEFAULT_MODEL = "gemini-3.8-flash"
MAX_PROMPT_CHARS = 8000
MAX_OUTPUT_TOKENS = 65536
MODEL_ID = re.compile(r"^[a-z0-9][a-z0-9.\-]{0,63}$")
EXTERNAL = ToolAnnotations(readOnlyHint=True, openWorldHint=True)
SOURCE_NOTE = (
    "Answer generated by Google Gemini, an external LLM. RFM's numeric engines "
    "(rfai, rfc, src) were not involved."
)
PRICING_URL = "https://ai.google.dev/gemini-api/docs/pricing"

# Tests inject an httpx.MockTransport here.
TRANSPORT: Optional[httpx.AsyncBaseTransport] = None


def _api_key() -> str:
    key = os.environ.get("GEMINI_API_KEY", "").strip()
    key_file = os.environ.get("GEMINI_API_KEY_FILE", "").strip()
    if not key and key_file:
        path = Path(key_file).expanduser()
        if path.is_file():
            key = path.read_text().strip()
    if not key:
        raise ToolError(
            "Gemini is not configured: set GEMINI_API_KEY or GEMINI_API_KEY_FILE "
            "on the server"
        )
    return key


def _model(model: Optional[str]) -> str:
    name = (model or os.environ.get("GEMINI_MODEL") or DEFAULT_MODEL).strip()
    name = name.removeprefix("models/")
    if not MODEL_ID.match(name):
        raise ToolError(f"invalid model id {name!r}")
    return name


async def _request(method: str, path: str, **kwargs: Any) -> dict[str, Any]:
    # The key goes in a header, never the URL, so it can't leak into access logs.
    headers = {"x-goog-api-key": _api_key()}
    async with httpx.AsyncClient(
        base_url=API_BASE, timeout=120, transport=TRANSPORT
    ) as client:
        try:
            response = await client.request(method, path, headers=headers, **kwargs)
        except httpx.HTTPError as exc:
            raise ToolError(f"Gemini request failed: {type(exc).__name__}") from None
    if response.status_code == 429:
        raise ToolError(
            "Gemini rate limit or free-tier quota reached (HTTP 429); try again "
            "later. No paid fallback is used."
        )
    if response.status_code >= 400:
        try:
            message = str(response.json().get("error", {}).get("message", ""))
        except ValueError:
            message = ""
        raise ToolError(f"Gemini API error {response.status_code}: {message[:300]}")
    result: dict[str, Any] = response.json()
    return result


def register_gemini_tools(mcp: FastMCP) -> None:
    @mcp.tool(annotations=EXTERNAL)
    async def ask_gemini(
        prompt: str, model: Optional[str] = None, max_output_tokens: int = 8192
    ) -> dict[str, Any]:
        """Send a free-form natural-language prompt to Google Gemini and return its
        answer. Gemini is an external LLM: none of RFM's numeric engines (rfai, rfc,
        src) process the prompt. Needs GEMINI_API_KEY on the server; the model
        defaults to GEMINI_MODEL or gemini-3.8-flash (see list_gemini_models)."""
        text = prompt.strip()
        if not text:
            raise ToolError("prompt must not be empty")
        if len(text) > MAX_PROMPT_CHARS:
            raise ToolError(f"prompt may be at most {MAX_PROMPT_CHARS} characters")
        if not 1 <= max_output_tokens <= MAX_OUTPUT_TOKENS:
            raise ToolError(f"max_output_tokens must be in [1, {MAX_OUTPUT_TOKENS}]")
        name = _model(model)
        body = {
            "contents": [{"role": "user", "parts": [{"text": text}]}],
            "generationConfig": {"maxOutputTokens": max_output_tokens},
        }
        data = await _request("POST", f"/models/{name}:generateContent", json=body)
        candidates = data.get("candidates") or []
        if not candidates:
            raise ToolError(
                f"Gemini returned no answer (promptFeedback: "
                f"{data.get('promptFeedback')})"
            )
        first = candidates[0]
        parts = (first.get("content") or {}).get("parts") or []
        answer = "".join(p.get("text", "") for p in parts if not p.get("thought"))
        return {
            "source": "google-gemini",
            "rfm_engines_used": False,
            "note": SOURCE_NOTE,
            "requested_model": name,
            "model_version": data.get("modelVersion"),
            "prompt": text,
            "answer": answer,
            "finish_reason": first.get("finishReason"),
            "usage": data.get("usageMetadata"),
        }

    @mcp.tool(annotations=EXTERNAL)
    async def list_gemini_models() -> dict[str, Any]:
        """List the Gemini models the server's API key can call with generateContent,
        straight from Google's authenticated model list."""
        models: list[dict[str, Any]] = []
        token: Optional[str] = None
        for _ in range(10):
            params: dict[str, Any] = {"pageSize": 1000}
            if token:
                params["pageToken"] = token
            data = await _request("GET", "/models", params=params)
            for item in data.get("models", []):
                if "generateContent" in item.get("supportedGenerationMethods", []):
                    models.append(
                        {
                            "id": str(item.get("name", "")).removeprefix("models/"),
                            "display_name": item.get("displayName"),
                            "input_token_limit": item.get("inputTokenLimit"),
                            "output_token_limit": item.get("outputTokenLimit"),
                        }
                    )
            token = data.get("nextPageToken")
            if not token:
                break
        return {
            "default_model": _model(None),
            "models": models,
            "note": (
                "Listed models are callable by this key; free-tier eligibility and "
                f"limits depend on the key's project, see {PRICING_URL}"
            ),
        }
